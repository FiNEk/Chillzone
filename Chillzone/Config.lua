-- Chillzone: настройки, которые меняет автор аддона (не игрок).
local ADDON, ns = ...

local C = {}
ns.Config = C

C.VERSION = "0.11.1"
C.PREFIX = "CHZSIGNED1" -- чат и сертификаты совместимы с 0.8
C.UNION_PREFIX = "CHZUNION1" -- решения главы отделены от старых каталогов офицеров

-- Главная гильдия: её глава — Король, главы остальных — Лорды, офицеры — Капитаны.
C.MAIN_GUILD = "Чиллзон"
-- Получатель запроса связи с вкладки «Объединение». Только адрес: управление определяет ранг в игре.
C.MAIN_GUILD_LEADER = "Вован Дубан"
-- Только подсказка для первоначального /who новичка; членство по названию не выдаётся.
C.GUILD_TOKEN = "Чиллзон"
-- Офицеры — звания с игровым флагом «офицер» (галочка в настройках гильдии), как в
-- ChillZoneUnion 0.6.
-- Если игра флаг не сказала (нет API, ошибка, пустой ответ), офицер — звание с номером не
-- больше OFFICER_RANK (0 — глава).
C.OFFICER_RANK = 1
-- Связные: игровое звание, которому глава гильдии доверяет связь между гильдиями
-- (как «Ветеран» в ChillZoneUnion). Сравнивается название звания целиком, без учёта
-- регистра и пробелов по краям: «Ветераны» и «Почётный ветеран» не подходят.
-- Глава, офицеры и связные гильдии могут быть её репортёром; в главной гильдии они же — реле.
-- Остальные участники не пересылают чужие сообщения. Пустая строка — только глава и офицеры.
-- Действует, только когда TRUST_ANY_MEMBER = false.
C.RELAY_RANK = "Ветеран"
-- true — репортёром и реле может быть любой участник с сертификатом; главы и офицеры
-- идут первыми. Пересылаемое всегда подписано автором, а роль реле не даёт права выдавать
-- сертификаты. false — только главы, офицеры и связные (RELAY_RANK).
C.TRUST_ANY_MEMBER = true

-- Состав объединения хранится в SavedVariables и подписывается текущим главой MAIN_GUILD.
-- Название подключаемой гильдии может быть любым; совпадения подстроки недостаточно.

-- Скрытые каналы прежних версий. Аддон в них больше не пишет: при входе выходит из них
-- и прячет их строки, чтобы сырой текст старых клиентов не попадал в чат.
C.OLD_CHANNELS = { "ChillzoneA", "ChillzoneH" }

---------------------------------------------------------------------------
-- Тайминги (секунды)
---------------------------------------------------------------------------
C.HELLO_EVERY = 60 -- H1 в гильдию
C.PEER_WINDOW = 180 -- кто считается «на связи» для выборов
C.SCAN_EVERY = 60 -- чтение ростера
C.ROSTER_LAG = 15 -- на столько ростер может отставать от игры: привет свежее не опровергается
C.REPORT_EVERY = 170 -- отчёт переписи репортёра
C.REPORT_IDLE = 600 -- без изменений — не чаще
C.LOGIN_QUIET = 70 -- первые секунды после входа репортёр молчит (слушает выборы)
-- Прежний репортёр после смены ещё пересылает гильдии RM по старой аренде, пока не
-- зарегистрировался новый (тому мешает LOGIN_QUIET), а гильдия принимает его RG.
C.REPORTER_HANDOVER = 120
C.Q1_GAP = 120 -- ответ на Q1 не чаще

-- Предупреждение об устаревшем аддоне (Update.lua). Версия считается вышедшей, когда новее
-- моей её назвали столько разных игроков (приветы H1 своей гильдии, отчёты R1 всех гильдий).
-- Названное помнится UPDATE_KEEP, не больше UPDATE_MAX игроков. Строка в чат — не раньше
-- UPDATE_TELL_AFTER после входа, чтобы не потеряться среди сообщений входа.
C.UPDATE_SOURCES = 2
C.UPDATE_KEEP = 14 * 86400
C.UPDATE_MAX = 40
C.UPDATE_TELL_AFTER = 20

C.FRESH = 15 * 60 -- онлайн и зоны свежие
C.TOTAL_KEEP = 24 * 3600 -- численность показывается
C.KEEP = 7 * 86400 -- хранение отчёта
C.CLAIM_TTL = 15 * 60 -- отправитель отчитывается за одну гильдию

C.RELAY_VERIFIED = 15 * 60 -- реле отвечало — годится для выбора
C.RELAY_WINDOW = 600 -- окно смены реле для гильдии
C.RELAY_TIMEOUT = 30 -- нет ответа на RP — реле офлайн
C.RELAY_DOWN = 600 -- офлайн-реле исключается
-- После входа реле из тройки шлёт своё и через других. Репортёр, заметивший его выход, до конца
-- RELAY_DOWN у него не регистрируется; запас — на следующую регистрацию.
C.RELAY_SETTLE = C.RELAY_DOWN + 30
C.RELAY_LEARNED_TTL = 14 * 86400
C.RELAY_LEARNED_MAX = 12
C.RELAY_HOLD = 20 -- очередь, пока ни одно реле не ответило
C.RELAY_DEDUPE = 300
C.RELAY_PER_MIN = 10 -- сообщений в минуту от одного автора через реле
C.RELAY_GOSSIP = 8 -- имён реле в RY
C.REG_EVERY = 170 -- RR

C.CHAT_DEDUPE = 120
C.CHAT_GAP = 1.5 -- у отправителя между строками
C.CHAT_PARTS = 3
C.CHAT_PART = 200 -- байт текста в части
C.CHAT_BURST = 6 -- у получателя: строк сразу от одного автора
C.CHAT_REFILL = 1.2 -- и по одной раз в столько секунд
C.CHAT_TIER_MIN = 60 -- строк в минуту на уровень
C.CHAT_HISTORY = 100

-- Членство остаётся коротким. Допуск издателя не заменяет сертификат участника.
C.AUTH_TTL = 7 * 24 * 3600
-- Отдельный допуск офицера: год автономной выдачи без корневого персонажа.
C.AUTH_ISSUER_TTL = 366 * 86400
-- Роль в сертификате (уровни C и L) подтверждена только столько секунд после выдачи.
C.AUTH_ROLE_TTL = 15 * 60
C.AUTH_RENEW = 10 * 60
C.AUTH_ROSTER_TTL = 120
C.AUTH_ANNOUNCE = 10 * 60 -- свой сертификат гильдии: при смене и не чаще раза в столько
C.AUTH_INTRODUCE = 30 * 60 -- сертификат автора одному получателю перед пакетом S1
-- Контакт гильдии объединения не в игре: столько не шептать ему решения главы.
C.UNION_CONTACT_RETRY = 30 * 60
-- Сколько выданных сертификатов издатель держит в очереди отправки. Они идут наравне с
-- чатом, поэтому массовая выдача задерживает строку не больше чем на столько сертификатов.
C.AUTH_ISSUE_QUEUE = 3
-- Проверок подписи в минуту: пакетов одного автора, пакетов через одного пересылающего
-- (реле, репортёр) и новых сертификатов от одного отправителя.
C.AUTH_AUTHOR_PER_MIN = 30
C.AUTH_HOP_PER_MIN = 120
C.AUTH_NEW_PER_MIN = 20
